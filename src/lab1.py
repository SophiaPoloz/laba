# Введення суми покупки користувачем
amount = float(input("Введіть суму покупки (грн): "))

# Перевірка, чи сума більша за нуль
if amount > 0:
    # Задаємо відсоток знижки (наприклад, 10%)
    discount_percent = 10
    
    # Розрахунок суми знижки та кінцевої вартості
    discount_value = amount * (discount_percent / 100)
    final_price = amount - discount_value
    
    # Виведення результатів з округленням до 2 знаків
    print("Відсоток знижки:", discount_percent, "%")
    print("Сума знижки:", round(discount_value, 2), "грн")
    print("Кінцева вартість до оплати:", round(final_price, 2), "грн")
else:
    # Повідомлення про неправильні дані
    print("Помилка: сума покупки має бути більшою за нуль.")
